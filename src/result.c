#include "arnm/result.h"

const char *arnm_result_to_string(arnm_result result) {
  static const char *messages[] = {
      [ARNM_SUCCESS] = "ARNM_SUCCESS",
      [ARNM_WARNING_ARENA_MEMORY_NOT_RECLAIMED] = "ARNM_WARNING_ARENA_MEMORY_NOT_RECLAIMED",
      [ARNM_WARNING_USED_DYNAMIC_ALLOCATION_FALLBACK] =
          "ARNM_WARNING_USED_DYNAMIC_ALLOCATION_FALLBACK",
      [ARNM_ERROR_NOT_IMPLEMENTED_YET] = "ARNM_ERROR_NOT_IMPLEMENTED_YET",
      [ARNM_ERROR_NOT_INITIALIZED] = "ARNM_ERROR_NOT_INITIALIZED",
      [ARNM_ERROR_INVALID_PARAM] = "ARNM_ERROR_INVALID_PARAM",
      [ARNM_ERROR_INVALID_ENUM_TYPE] = "ARNM_ERROR_INVALID_ENUM_TYPE",
      [ARNM_ERROR_INVALID_STATE] = "ARNM_ERROR_INVALID_STATE",
      [ARNM_ERROR_NULL_POINTER] = "ARNM_ERROR_NULL_POINTER",
      [ARNM_ERROR_ARITHMETIC_OVERFLOW] = "ARNM_ERROR_ARITHMETIC_OVERFLOW",
      [ARNM_ERROR_OUT_OF_MEMORY] = "ARNM_ERROR_OUT_OF_MEMORY",
      [ARNM_ERROR_ARRAY_INDEX_OUT_OF_BOUNDS] = "ARNM_ERROR_ARRAY_INDEX_OUT_OF_BOUNDS",
      [ARNM_ERROR_RESOURCE_EXHAUSTED] = "ARNM_ERROR_RESOURCE_EXHAUSTED",
      [ARNM_ERROR_RESOURCE_SIZE_EXCEED] = "ARNM_ERROR_RESOURCE_SIZE_EXCEED",
      [ARNM_ERROR_RESOURCE_IN_USE] = "ARNM_ERROR_RESOURCE_IN_USE",
      [ARNM_ERROR_DECODE_FAILED] = "ARNM_ERROR_DECODE_FAILED",
      [ARNM_ERROR_ENCODE_FAILED] = "ARNM_ERROR_ENCODE_FAILED",
      [ARNM_ERROR_DESTINATION_BUFFER_TO_SMALL] = "ARNM_ERROR_DESTINATION_BUFFER_TO_SMALL",
      [ARNM_ERROR_ENUM_UNHANDLED] = "ARNM_ERROR_ENUM_UNHANDLED",
      [ARNM_ERROR_ENUM_UNKNOWN] = "ARNM_ERROR_ENUM_UNKNOWN",
  };

  if (result < 0 || result >= (int)(sizeof(messages) / sizeof(messages[0]))) {
    return "ARNM_ERROR_UNKNOWN";
  }
  const char *msg = messages[result];
  return msg ? msg : "ARNM_ERROR_UNKNOWN";
}
